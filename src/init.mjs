// `storyshot init <url>`: inspect the page and write a starter storyboard that already
// uses verified targets, so an agent edits a working file instead of writing YAML from scratch.
import fs from 'node:fs';
import path from 'node:path';
import { inspect } from './inspect.mjs';
import { PURPOSES, defaultStoryboard } from './config.mjs';
import { loginAdvice } from './auth.mjs';

const q = (s) => JSON.stringify(String(s));
// The product's name from the page title: its first part ("Squoosh | Image compressor" → "Squoosh",
// "Hoppscotch • Open source API development ecosystem • Hoppscotch" → "Hoppscotch"),
// or the repo on a code host ("GitHub - boheling/storyshot: Ask…" → "storyshot"). Only spaced
// separators split, so a hyphenated name (Tic-Tac-Toe) stays whole.
export function productName(title, host) {
  const segs = String(title ?? '').split(/\s+[|｜—–·•∙‧-]\s+|:\s+/).map((s) => s.trim()).filter(Boolean);
  const repo = segs.find((s) => /^[\w.-]+ ?\/ ?[\w.-]+$/.test(s));
  return repo ? repo.split('/')[1].trim() : segs[0] ?? host;
}
const tgt = (t) => (typeof t === 'string' ? q(t) : `{ ${Object.entries(t).map(([k, v]) => `${k}: ${typeof v === 'string' ? q(v) : v}`).join(', ')} }`);

export async function initStoryboard(url, { purpose = 'pitch', topic, file, storageState, ignoreHTTPSErrors = false, viewport = { width: 1600, height: 900 } } = {}) {
  if (!PURPOSES[purpose]) throw new Error(`purpose must be one of ${Object.keys(PURPOSES).join(', ')}`);
  file ??= defaultStoryboard(url, purpose, topic);
  if (fs.existsSync(file)) throw new Error(`${file} already exists — edit it, or choose another path`);
  const page = await inspect(url, { viewport, storageState, ignoreHTTPSErrors, outDir: path.join(path.dirname(path.resolve(file)), '.storyshot', 'inspect') });
  if (page.login?.wall) {
    throw new Error(`${url} asks to log in (${page.login.reason})${storageState ? ' even with the saved session — it has probably expired, log in again' : ''}. ` +
      `${loginAdvice(url)} Then run init again with that session (MCP: storage_state, CLI: --storage).`);
  }
  const host = new URL(page.url).host.replace(/^www\./, '');
  const name = path.basename(file).replace(/\.ya?ml$/, '');
  const narrated = purpose !== 'pitch' && purpose !== 'docs';
  const h1 = page.headings.find((h) => h.tag === 'h1') ?? page.headings[0];
  const risky = /delete|remove|clear|reset|sign ?out|log ?out|close|dismiss|cancel|unsubscribe|undo|redo/i;
  const nice = /get started|try|start|demo|sample|example|new|create|sign up|explore|learn more|open/i;
  const fold = page.elements.filter((e) => e.y < viewport.height && e.y > 80 && !risky.test(`${e.name ?? ''} ${e.shows ?? ''}`));
  fold.sort((a, b) => nice.test(`${b.name} ${b.shows}`) - nice.test(`${a.name} ${a.shows}`));
  const dismiss = page.elements.find((e) => typeof e.target === 'object' && e.target.role && /accept|agree|dismiss|got it|close|×|no thanks/i.test(e.name ?? '') && e.y < 900);
  const cta = fold.find((e) => e.role === 'button' || e.kind === 'pointer') ?? fold.find((e) => e.role === 'link' && !/^#/.test(e.href ?? '')) ?? fold[0];
  const dur = (d) => (purpose === 'pitch' ? `\n    duration: ${d}` : '');
  const say = (s) => (narrated ? `\n    say: ${s}` : '');

  const yaml = `# Storyshot storyboard (${purpose}) — generated by \`storyshot init\` from ${page.url}
# Edit freely. Full reference: \`storyshot guide\` or the MCP tool storyboard_guide.
# Loop: storyshot check → storyshot render${narrated ? ' --draft' : ''} → look at preview.jpg → fix → repeat.
name: ${name}
url: ${page.url}
purpose: ${purpose}
out: ${name}.mp4
${storageState ? `storageState: ${path.relative(path.dirname(path.resolve(file)), path.resolve(storageState)).split(path.sep).join('/')}   # saved login (never commit it)\n` : ''}${ignoreHTTPSErrors ? 'ignoreHTTPSErrors: true   # internal site with a self-signed certificate\n' : ''}${narrated ? 'voice: { provider: kokoro }        # free, local, English. For the final: { provider: elevenlabs, voice: <voice id> } + ELEVENLABS_API_KEY' : '# voice: { provider: kokoro }      # optional voiceover; add `say:` lines to steps'}

${purpose === 'pitch' ? `intro:                             # title card before the recording (promos; optional for tutorials/lessons)
  title: ${q(productName(page.title, host))}
  subtitle: TODO the one-line promise, with the **key words** in bold
${PURPOSES[purpose]?.frame ? '# frame: false                     # the recording sits in a browser window on a backdrop; false = full frame\n' : ''}
` : purpose === 'tutorial' || purpose === 'course' ? `# intro: { title: TODO, subtitle: TODO }   # optional title card (e.g. "How to export a report")

` : ''}setup:                             # runs before recording; clean the frame here${dismiss ? `\n  - dismiss: ${tgt(dismiss.target)}` : '\n  # - dismiss: { role: button, name: Accept cookies }'}

steps:
  - caption: ${q(h1?.text?.slice(0, 50) || page.title || host)}${say('TODO one sentence on what this product does.')}${dur(2.5)}
    zoom: { target: ${h1 ? 'h1' : '{ x: 0.5, y: 0.35 }'}, scale: 1.2, start: 0.3 }
    actions:
      - pause: 600
      - move: { x: 0.5, y: 0.45, ms: 1200 }

  - caption: TODO what this click shows${say('TODO tell the viewer what to do and why.')}${dur(2.5)}
    actions:
      - click: ${cta ? tgt(cta.target) : '{ role: button, name: TODO }'}${cta ? `   # ${cta.href ? `→ ${cta.href}` : 'first clickable above the fold'}` : ''}
      - networkIdle: true
      - pause: 800

  # TODO: add the steps of your flow. For pages you can only reach by clicking through,
  # run \`storyshot inspect ${file} --after <step>\` to list verified targets at that point.

end_card:
  title: ${q(productName(page.title, host))}
  cta: ${q(`Try it at ${host}`)}${narrated ? `\n  say: ${q(`Try it at ${host}.`)}` : ''}

# ── Verified targets on ${page.url} (each matches exactly one visible element) ──
${page.elements.slice(0, 40).map((e) => `#   y=${String(e.y).padEnd(5)} ${tgt(e.target)}${e.href ? `  → ${e.href}` : ''}`).join('\n')}
# Headings: ${page.headings.slice(0, 8).map((h) => `${h.tag} "${h.text.slice(0, 40)}"`).join(' · ')}
# Sections: ${page.anchors.map((a) => `#${a.id}`).join(' ') || '(none)'}
`;
  fs.mkdirSync(path.dirname(path.resolve(file)), { recursive: true });
  fs.writeFileSync(file, yaml);
  return { file: path.resolve(file), yaml, screenshot: page.screenshot, inspect: page.text, login: page.login };
}

// `storyshot init --purpose explainer --topic <topic>`: no web app, so nothing to inspect — a storyboard
// of three scene steps and a starter scene file for each, timed to its narration with window.__storyshot.
export function initExplainer({ topic, file, lang = 'en', portrait = false } = {}) {
  if (!topic) throw new Error('an explainer is named by its topic: --topic "how a TaqMan probe works" (MCP: topic)');
  file ??= defaultStoryboard(null, 'explainer', topic);
  if (fs.existsSync(file)) throw new Error(`${file} already exists — edit it, or choose another path`);
  const name = path.basename(file).replace(/\.ya?ml$/, '');
  const dir = path.dirname(path.resolve(file));
  const zh = /^zh/i.test(lang);
  const [W, H] = portrait ? [1080, 1920] : [1920, 1080];
  // Four steps, not three: a recap re-counts what the film said and then runs out, which a viewer hears
  // as the film being cut off. The last step is the ending itself (`storyshot guide`: "How an explainer ends").
  const scenes = [1, 2, 3].map((k) => ({ id: `${name}-s${k}`.replace(/[^a-z0-9-]/gi, '-'), rel: `scenes/${name}-${k}.html` }));
  scenes.push({ id: `${name}-close`.replace(/[^a-z0-9-]/gi, '-'), rel: `scenes/${name}-close.html` });
  const say = zh
    ? ['TODO 一个观众会问的问题，一两句话。', 'TODO 用一个具体例子回答，每个短句对应画面上的一个变化。', 'TODO 把讲过的再数一遍。',
       'TODO 结尾：这件事到底意味着什么（一句在第一场说不出来的话）；哪些还没有答案；留给观众的一句话，落在片子自己的那张图上。']
    : ['TODO the question a viewer would ask, in one or two sentences.', 'TODO answer it with one concrete example, one change on screen per phrase.',
       'TODO count back over what the film showed, one line each.',
       'TODO the ending. What this actually means (the sentence you could not have said in scene 1), what is still open, and one thought to leave with, on the film\'s own picture.'];
  const note = [
    '\n    # scene: { file: …, title: Chapter title, lead: 0.5, tail: 0.8 }   (lead: seconds before the voice starts)', '', '',
    zh ? '\n    # 回顾数完就停，所以听起来没有结局；这一场才是结局。最后一下落在最后一句话上，\n    # 而且到最后一帧还在动（一条还在画的线，一道还在合的帘子），别停在一张满画面上。'
       : '\n    # The recap stops rather than ends; this scene is the ending. Land its last move ON the final words,\n    # and leave something still moving at the last frame — not a held frame of the film\'s fullest moment.',
  ];
  const yaml = `# Storyshot storyboard (explainer) — every step is a scene: an animation you write as a HyperFrames
# composition (scenes/*.html), timed to the step's narration. Reference: \`storyshot guide\` ("Scenes and explainers").
# Loop: write the say: lines → storyshot cues (when each phrase is spoken) → write the scenes with S.at(k)
#       → storyshot scene ${path.basename(file)} --step N (stills + checks) → storyshot render → look → fix.
name: ${name}
purpose: explainer
out: ${name}.mp4
${zh ? 'lang: zh\nvoice: { provider: qwen, voice: dylan }      # free, local (Apple Silicon); elsewhere kokoro zf_001' : 'voice: { provider: kokoro }                  # free, local'}
${portrait ? 'aspect: portrait                                 # 9:16, 1080x1920: a phone held upright, and every short-video feed.\n                                                 # Write every scene as one column: `storyshot guide` ("Portrait").\n' : ''}subtitles: true                                  # an .srt beside the video, which is the right one for an explainer: the
                                                 # scenes already carry text, and \`burn\` lights the words up at the bottom
                                                 # of the picture, pulling the eye off the drawing for the whole film.
                                                 # Burn them for social video or a feed that autoplays muted, and say so.
scenes: { css: scenes/kit/look.css }             # the look sheet: this film's colour, type and composition, shared by every
                                                 # scene. It starts as a grey pencil test. Decide the look from the subject
                                                 # BEFORE drawing (\`storyshot guide\`: "Design the film before the first scene").
ground: light                                    # light | dark: the film's ground, from the look sheet. Paper for a subject that
                                                 # is taught, printed or voted on; dark for a mechanism, an instrument or anything
                                                 # that glows. The cards follow it; paint every scene to match.
theme: { accent: "#5c5c5c", ink: "#26262a", paper: "#e3e3e0" }   # the look sheet's three main colours, repeated here so
                                                 # the intro and end cards belong to the same film. accent: the one colour
                                                 # that points, so it has to read on the ground. paper: the ground itself.

steps:
${scenes.map((sc, k) => `  - scene: ${sc.rel}${note[k] ?? ''}
    say: ${say[k]}`).join('\n\n')}
`;
  fs.mkdirSync(path.join(dir, 'scenes', 'assets'), { recursive: true });
  fs.mkdirSync(path.join(dir, 'scenes', 'kit'), { recursive: true });
  const look = path.join(dir, 'scenes', 'kit', 'look.css');
  if (!fs.existsSync(look)) fs.writeFileSync(look, starterLook(W, H));
  for (const sc of scenes) fs.writeFileSync(path.join(dir, sc.rel), starterScene(sc.id, W, H));
  fs.writeFileSync(file, yaml);
  return { file: path.resolve(file), yaml, look, scenes: scenes.map((sc) => path.join(dir, sc.rel)) };
}

// The look sheet a new explainer starts with. It is grey on purpose: a pencil test, the way an animatic
// is, so that no hue, face or layout is inherited by a film that never chose one. The last starter was
// warm paper with an orange accent, and that is what half the films made from it looked like.
function starterLook(W, H) {
  const u = Math.min(H, W * 1.15) / 1080; // sizes are written for 1920x1080; a portrait frame sizes them by its width
  const px = (n) => `${Math.round(n * u)}px`;
  return `/* The look sheet: how this film looks, decided once, before any scene is drawn.
   \`storyshot guide\`: "Design the film before the first scene".

   Everything below is a grey pencil test. Replace all four parts with choices that come from this
   film's subject and its audience, then delete the "storyshot-look" line.

   1. Colour       four to six named values, one job each: the ground, the ink, the one colour that
                   points, a colour for each thing the story tracks, a quiet tone for structure.
                   Take them from the subject: what it is printed on, drawn with, lit by.
   2. Type         one family, or two that are plainly different, and four or five sizes. Say what
                   each size is for. The lettering the subject already comes with is the place to look.
   3. Composition  where the object sits, which edge the words hang from, how a label reaches its part.
   4. One bold thing  what a viewer will remember this film looked like. The rest stays quiet.

   Then read it back: would this sheet fit a film on any other subject? Whatever would, change.

   storyshot-look: placeholder
*/
:root {
  /* 1. colour (also repeat ground, ink and point as theme.paper, theme.ink and theme.accent in the storyboard) */
  --ground: #e3e3e0;
  --quiet: #b9b9b5;      /* structure: rules, leader lines, what is not being talked about */
  --point: #5c5c5c;      /* the one colour that points */
  /* --ink comes from theme.ink */

  /* 2. type */
  --face: var(--font);   /* theme.font, or a family of your own: put Name.woff2 in scenes/assets/ and add
                            @font-face { font-family: 'Name'; src: url('../assets/Name.woff2') format('woff2') } above */
  --t-label: ${px(34)};     /* a name on a part */
  --t-body: ${px(46)};      /* a sentence */
  --t-head: ${px(76)};      /* what this scene is about */
  --t-figure: ${px(200)};   /* a number or a word that is itself the point */

  /* 3. composition */
  --edge: ${px(150)};       /* the one edge the words hang from */
}
/* Every scene's root: <div id="…" class="film" …>. The ground is written as a colour here (not a
   variable) so storyshot can read whether the film is light or dark. */
.film { position: absolute; inset: 0; overflow: hidden; background: #e3e3e0; color: var(--ink); font-family: var(--face); }
.film .label { font-size: var(--t-label); line-height: 1.25; font-weight: 500; }
.film .head { font-size: var(--t-head); line-height: 1.1; font-weight: 650; letter-spacing: -0.02em; }
`;
}

// A scene that already works, drawn from the look sheet: the object takes the frame, one label reaches
// it with a leader line, and the words hang from one edge. Replace its picture; keep the contract
// (template, matching ids, timeline registered) and keep the look in the sheet, not in the scene.
function starterScene(id, W, H) {
  const tall = H > W;
  const ox = Math.round(W * (tall ? 0.14 : 0.46)), oy = Math.round(H * (tall ? 0.36 : 0.2)), ow = Math.round(W * (tall ? 0.72 : 0.44)), oh = Math.round(H * (tall ? 0.4 : 0.6));
  const hx = tall ? ox : 'var(--edge)', hy = Math.round(H * (tall ? 0.14 : 0.3)), hw = Math.round(W * (tall ? 0.72 : 0.3));
  const lx = tall ? ox : Math.round(W * 0.078), ly = Math.round(H * (tall ? 0.82 : 0.62));
  const p = (n) => `${n}px`;
  return `<template>
  <style>
    #${id}-head { position: absolute; left: ${typeof hx === 'number' ? p(hx) : hx}; top: ${p(hy)}; width: ${p(hw)}; }
    #${id}-obj { position: absolute; left: ${p(ox)}; top: ${p(oy)}; width: ${p(ow)}; height: ${p(oh)}; }
    #${id}-obj rect { fill: none; stroke: var(--ink); stroke-width: 5; }
    #${id}-obj path { fill: none; stroke: var(--point); stroke-width: 4; stroke-dasharray: 1; }
    #${id}-name { position: absolute; left: ${typeof hx === 'number' ? p(lx) : hx}; top: ${p(ly)}; color: var(--point); }
  </style>
  <div id="${id}" class="film" data-composition-id="${id}" data-width="${W}" data-height="${H}">
    <div id="${id}-head" class="head">TODO what this scene is about</div>
    <!-- the object: at least 40% of the frame, drawn, not an icon -->
    <svg id="${id}-obj" viewBox="0 0 ${ow} ${oh}">
      <rect id="${id}-box" x="4" y="4" width="${ow - 8}" height="${oh - 8}" rx="6" pathLength="1" style="stroke-dasharray: 1"/>
      <path id="${id}-lead" d="M ${Math.round(ow * 0.5)} ${Math.round(oh * 0.5)} L ${tall ? Math.round(ow * 0.1) : 0} ${tall ? oh : Math.round(oh * 0.76)}" pathLength="1"/>
    </svg>
    <div id="${id}-name" class="label">TODO the part the voice just named</div>
  </div>
  <script>
    (function () {
      // S.at(k): when phrase k of this step's say: line starts (S.end(k): ends); S.duration, S.width, S.height,
      // S.safeBottom (px burned-in subtitles take; 0 without \`subtitles: burn\`), S.cues ([{ text, t, end }]). Run \`storyshot cues\`.
      const S = window.__storyshot;
      const tl = gsap.timeline({ paused: true });
      // one move per phrase: the object is drawn, then the label reaches for its part
      tl.fromTo('#${id}-head', { opacity: 0 }, { opacity: 1, duration: 0.4, ease: 'power2.out' }, S.at(0));
      tl.fromTo('#${id}-box', { strokeDashoffset: 1 }, { strokeDashoffset: 0, duration: 1.1, ease: 'power2.inOut', autoRound: false }, S.at(0, 0.2));
      tl.fromTo('#${id}-lead', { strokeDashoffset: 1 }, { strokeDashoffset: 0, duration: 0.5, ease: 'power2.out', autoRound: false }, S.at(1));
      tl.fromTo('#${id}-name', { opacity: 0 }, { opacity: 1, duration: 0.3, ease: 'power2.out' }, S.at(1, 0.3));
      window.__timelines['${id}'] = tl;
    })();
  </script>
</template>
`;
}
