// `storyshot init <url>`: inspect the page and write a starter storyboard that already
// uses verified targets, so an agent edits a working file instead of writing YAML from scratch.
import fs from 'node:fs';
import path from 'node:path';
import { inspect } from './inspect.mjs';
import { PURPOSES, defaultStoryboard } from './config.mjs';
import { loginAdvice } from './auth.mjs';

const q = (s) => JSON.stringify(String(s));
const tgt = (t) => (typeof t === 'string' ? q(t) : `{ ${Object.entries(t).map(([k, v]) => `${k}: ${typeof v === 'string' ? q(v) : v}`).join(', ')} }`);

export async function initStoryboard(url, { purpose = 'pitch', topic, file, storageState, ignoreHTTPSErrors = false, viewport = { width: 1600, height: 900 } } = {}) {
  if (!PURPOSES[purpose]) throw new Error(`purpose must be one of ${Object.keys(PURPOSES).join(', ')}`);
  file ??= defaultStoryboard(url, purpose, topic);
  if (fs.existsSync(file)) throw new Error(`${file} already exists — edit it, or choose another path`);
  const page = await inspect(url, { viewport, storageState, ignoreHTTPSErrors, outDir: path.join(path.dirname(path.resolve(file)), '.storyshot', 'inspect') });
  if (page.login?.wall) {
    throw new Error(`${url} asks to log in (${page.login.reason})${storageState ? ' even with the saved session — it has probably expired, log in again' : ''}. ` +
      `${loginAdvice(url)} Then run init again with that session (MCP: storage_state, CLI: --storage).`);
  }
  const host = new URL(page.url).host.replace(/^www\./, '');
  const name = path.basename(file).replace(/\.ya?ml$/, '');
  const narrated = purpose !== 'pitch' && purpose !== 'docs';
  const h1 = page.headings.find((h) => h.tag === 'h1') ?? page.headings[0];
  const risky = /delete|remove|clear|reset|sign ?out|log ?out|close|dismiss|cancel|unsubscribe|undo|redo/i;
  const nice = /get started|try|start|demo|sample|example|new|create|sign up|explore|learn more|open/i;
  const fold = page.elements.filter((e) => e.y < viewport.height && e.y > 80 && !risky.test(`${e.name ?? ''} ${e.shows ?? ''}`));
  fold.sort((a, b) => nice.test(`${b.name} ${b.shows}`) - nice.test(`${a.name} ${a.shows}`));
  const dismiss = page.elements.find((e) => typeof e.target === 'object' && e.target.role && /accept|agree|dismiss|got it|close|×|no thanks/i.test(e.name ?? '') && e.y < 900);
  const cta = fold.find((e) => e.role === 'button' || e.kind === 'pointer') ?? fold.find((e) => e.role === 'link' && !/^#/.test(e.href ?? '')) ?? fold[0];
  const dur = (d) => (purpose === 'pitch' ? `\n    duration: ${d}` : '');
  const say = (s) => (narrated ? `\n    say: ${s}` : '');

  const yaml = `# Storyshot storyboard (${purpose}) — generated by \`storyshot init\` from ${page.url}
# Edit freely. Full reference: \`storyshot guide\` or the MCP tool storyboard_guide.
# Loop: storyshot check → storyshot render${narrated ? ' --draft' : ''} → look at preview.jpg → fix → repeat.
name: ${name}
url: ${page.url}
purpose: ${purpose}
out: ${name}.mp4
${storageState ? `storageState: ${path.relative(path.dirname(path.resolve(file)), path.resolve(storageState)).split(path.sep).join('/')}   # saved login (never commit it)\n` : ''}${ignoreHTTPSErrors ? 'ignoreHTTPSErrors: true   # internal site with a self-signed certificate\n' : ''}${narrated ? 'voice: { provider: kokoro }        # free, local, English. For the final: { provider: elevenlabs, voice: <voice id> } + ELEVENLABS_API_KEY' : '# voice: { provider: kokoro }      # optional voiceover; add `say:` lines to steps'}

${purpose === 'pitch' ? `intro:                             # title card before the recording (promos; optional for tutorials/lessons)
  title: ${q(page.title.split(/[|—–-]/)[0].trim() || host)}
  subtitle: TODO the one-line promise, with the **key words** in bold
${PURPOSES[purpose]?.frame ? '# frame: false                     # the recording sits in a browser window on a backdrop; false = full frame\n' : ''}
` : purpose === 'tutorial' || purpose === 'course' ? `# intro: { title: TODO, subtitle: TODO }   # optional title card (e.g. "How to export a report")

` : ''}setup:                             # runs before recording; clean the frame here${dismiss ? `\n  - dismiss: ${tgt(dismiss.target)}` : '\n  # - dismiss: { role: button, name: Accept cookies }'}

steps:
  - caption: ${q(h1?.text?.slice(0, 50) || page.title || host)}${say('TODO one sentence on what this product does.')}${dur(2.5)}
    zoom: { target: ${h1 ? 'h1' : '{ x: 0.5, y: 0.35 }'}, scale: 1.2, start: 0.3 }
    actions:
      - pause: 600
      - move: { x: 0.5, y: 0.45, ms: 1200 }

  - caption: TODO what this click shows${say('TODO tell the viewer what to do and why.')}${dur(2.5)}
    actions:
      - click: ${cta ? tgt(cta.target) : '{ role: button, name: TODO }'}${cta ? `   # ${cta.href ? `→ ${cta.href}` : 'first clickable above the fold'}` : ''}
      - networkIdle: true
      - pause: 800

  # TODO: add the steps of your flow. For pages you can only reach by clicking through,
  # run \`storyshot inspect ${file} --after <step>\` to list verified targets at that point.

end_card:
  title: ${q(page.title.split(/[|—–-]/)[0].trim() || host)}
  cta: ${q(`Try it at ${host}`)}${narrated ? `\n  say: ${q(`Try it at ${host}.`)}` : ''}

# ── Verified targets on ${page.url} (each matches exactly one visible element) ──
${page.elements.slice(0, 40).map((e) => `#   y=${String(e.y).padEnd(5)} ${tgt(e.target)}${e.href ? `  → ${e.href}` : ''}`).join('\n')}
# Headings: ${page.headings.slice(0, 8).map((h) => `${h.tag} "${h.text.slice(0, 40)}"`).join(' · ')}
# Sections: ${page.anchors.map((a) => `#${a.id}`).join(' ') || '(none)'}
`;
  fs.mkdirSync(path.dirname(path.resolve(file)), { recursive: true });
  fs.writeFileSync(file, yaml);
  return { file: path.resolve(file), yaml, screenshot: page.screenshot, inspect: page.text, login: page.login };
}
